        'একাত্তর', 'বাহাত্তর', 'তিয়াত্তর', 'চুয়াত্তর', 'পঁচাত্তর', 'ছিয়াত্তর', 'সাতাত্তর', 'আটাত্তর', 'ঊনআশি', 'আশি',
        'একাশি', 'বিরাশি', 'তিরাশি', 'চুরাশি', 'পঁচাশি', 'ছিয়াশি', 'সাতাশি', 'আটাশি', 'ঊননব্বই', 'নব্বই',
        'একানব্বই', 'বিরানব্বই', 'তিরানব্বই', 'চুরানব্বই', 'পঁচানব্বই', 'ছিয়ানব্বই', 'সাতানব্বই', 'আটানব্বই', 'নিরানব্বই',
    ];

    public static function digits(string|int|float $value): string
    {
        return strtr((string) $value, ['0' => '০', '1' => '১', '2' => '২', '3' => '৩', '4' => '৪', '5' => '৫', '6' => '৬', '7' => '৭', '8' => '৮', '9' => '৯']);
    }

    public static function words(int $n): string
    {
        if ($n === 0) {
            return self::ONES[0];
        }
        if ($n < 0) {
            return 'ঋণাত্মক '.self::words(-$n);
        }

        $parts = [];
        $crore = intdiv($n, 10000000);
        $n %= 10000000;
        if ($crore) {
            $parts[] = self::words($crore).' কোটি';
        }
        foreach ([[100000, 'লক্ষ'], [1000, 'হাজার'], [100, 'শত']] as [$size, $name]) {
            $chunk = intdiv($n, $size);
            $n %= $size;
            if ($chunk) {
                $parts[] = self::ONES[$chunk].' '.$name;
            }
        }
        if ($n) {
            $parts[] = self::ONES[$n];
        }

        return implode(' ', $parts);
    }

    /** "একানব্বই হাজার দুই শত টাকা মাত্র" (+ পয়সা when there is a fraction). */
    public static function taka(float $amount): string
    {
        $amount = round(abs($amount), 2);
        $taka   = (int) floor($amount);
        $paisa  = (int) round(($amount - $taka) * 100);

        return self::words($taka).' টাকা'.($paisa ? ' '.self::words($paisa).' পয়সা' : '').' মাত্র';
    }
}
